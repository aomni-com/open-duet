export function parentSessionPrompt(args: {
  parentSessionId: string
  workspaceSlug: string | undefined
}): string {
  const workspaceSlug = args.workspaceSlug ?? '$WORKSPACE_SLUG'
  const workspaceSlugSetup =
    args.workspaceSlug === undefined
      ? [
          'First resolve the workspace slug:',
          '',
          '```bash',
          'WORKSPACE_SLUG="$(curl -sS "$DUET_API_URL/v1/whoami" \\',
          '  -H "Authorization: Bearer $DUET_API_KEY" | jq -er \'.workspaces[0].slug\')"',
          '```',
          '',
        ]
      : []

  return [
    '# Parent session',
    '',
    `This session was started by parent session \`${args.parentSessionId}\`.`,
    '',
    ...workspaceSlugSetup,
    'First, check who started your current turn. If the input you are answering',
    'is a `session_message` from this parent, the parent is blocked waiting for',
    'your turn to end — a message sent back to it will never be read, because it',
    'cannot end its turn until you end yours. End your turn by asking instead:',
    'your question resolves its wait, and the answer arrives as your next turn.',
    '',
    'Use the recipe below only when the parent is idle — reporting a finished',
    'background job, or raising something new. Generate one request UUID and',
    'reuse it after an ambiguous disconnect. `sourceSessionId` attributes your',
    'message to this session; without it the message is attributed to whoever',
    'owns the credential:',
    '',
    '```bash',
    'CLIENT_REQUEST_ID="$(bun -e \'console.log(crypto.randomUUID())\')"',
    `WAIT_PATH="/v1/ws/${workspaceSlug}/agent/sessions/${args.parentSessionId}/messages/wait"`,
    'WAIT_BODY="$(mktemp)"',
    'REQUEST_BODY="$(jq -n --arg id "$CLIENT_REQUEST_ID" --arg sid "$DUET_SESSION_ID" \\',
    '  \'{prompt:"<question>",behavior:"follow_up",sourceSessionId:$sid,clientRequestId:$id}\')"',
    'WAIT_STATUS="$(curl -sS -o "$WAIT_BODY" -w \'%{http_code}\' -X POST \\',
    '  "$DUET_API_URL$WAIT_PATH" \\',
    '  -H "Authorization: Bearer $DUET_API_KEY" \\',
    "  -H 'Content-Type: application/json' \\",
    '  -d "$REQUEST_BODY")"',
    'while [ "$WAIT_STATUS" = 202 ]; do',
    '  WAIT_STATUS="$(curl -sS -o "$WAIT_BODY" -w \'%{http_code}\' -X POST \\',
    '    "$DUET_API_URL$WAIT_PATH" \\',
    '    -H "Authorization: Bearer $DUET_API_KEY" \\',
    "    -H 'Content-Type: application/json' \\",
    '    -d "$REQUEST_BODY")"',
    'done',
    'INPUT_SEQ="$(jq -er .inputSeq "$WAIT_BODY")"',
    '```',
    '',
    '`follow_up` is required here. Use `steer` only for an explicit interruption.',
    'A `note` does not wake the parent runner. If a foreground connection cannot',
    'be held open, use ordinary submission plus history polling.',
    '',
    'The wait response contains the correlated terminal. If you need more context',
    'about how the result was produced, query history after its `inputSeq`.',
    'Delivered message envelopes carry the same durable sequence: a `seq`',
    'attribute you see in your own input is a valid strictly-after cursor here.',
    '',
    '```bash',
    'curl -sS \\',
    `  "$DUET_API_URL/v1/ws/${workspaceSlug}/agent/sessions/${args.parentSessionId}/history?order=asc&afterSeq=$INPUT_SEQ" \\`,
    '  -H "Authorization: Bearer $DUET_API_KEY"',
    '```',
    '',
    'Read timeline rows from `items`. Follow every opaque `nextCursor`, even',
    'after a short or empty page, and stop only when it is `null`.',
    '',
    'The user may also read this session, so address them normally.',
    '',
  ].join('\n')
}
