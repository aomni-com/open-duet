export type PublicApiEndpointCategory = (typeof PUBLIC_API_ENDPOINT_CATEGORIES)[number]
type PublicApiMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'
export interface PublicApiCollectionMetadata {
  readonly order: string
  readonly cursorDomain: string
  readonly migrationSlice?: '02' | '03' | '04a' | '04b' | '04c' | '16' | '17'
}

export type PublicApiSuccessResponseMetadata =
  | {
      readonly status: number
      readonly responseSchema: ZodType
      readonly responseBody?: never
    }
  | {
      readonly status: number
      readonly responseSchema?: never
      readonly responseBody: 'binary' | 'redirect' | 'none'
    }

type PublicApiScope =
  | 'public'
  | 'api_key'
  | 'browser_session'
  | 'human'
  | 'workspace_member'
  | `ws:{workspaceSlug}:${string}`

/**
 * Public HTTP facts consumed by documentation and other generated surfaces.
 * Route implementations own orchestration; this registry owns what may be
 * promised to third-party developers.
 */
export interface PublicApiEndpointMetadata {
  readonly id: string
  readonly category: PublicApiEndpointCategory
  readonly method: PublicApiMethod
  readonly path: `/v1/${string}`
  readonly summary: string
  readonly scope: PublicApiScope | readonly PublicApiScope[]
  readonly additionalScopes?: readonly PublicApiScope[]
  readonly requestSchema?: ZodType
  readonly querySchema?: ZodType
  readonly responseSchema?: ZodType
  /**
   * Status-aware success variants for operations whose successful outcomes do
   * not share one body. This replaces `responseSchema`/`responseBody` for that
   * operation; ordinary single-outcome endpoints keep the compact fields.
   */
  readonly successResponses?: readonly [
    PublicApiSuccessResponseMetadata,
    PublicApiSuccessResponseMetadata,
    ...PublicApiSuccessResponseMetadata[],
  ]
  readonly collection?: PublicApiCollectionMetadata
  readonly requestBody?: 'binary' | 'none'
  /**
   * `binary` streams bytes; `redirect` answers 3xx; `none` answers with no body.
   * In all three cases there is no schema to
   * publish, which is what this field says instead of leaving one absent.
   */
  readonly responseBody?: 'binary' | 'redirect' | 'none'
  /**
   * Operation-specific structured 4xx bodies beyond the bare `{ error: code }`
   * shape that third-party clients must be able to parse (e.g. the 409
   * link-conflict bodies on the files surface). Common authenticated-protocol
   * errors such as the general API rate limit are rendered separately.
   */
  readonly errorSchema?: ZodType
  readonly streaming?: 'sse'
  readonly idempotent?: boolean
  readonly requestHeaders?: readonly {
    readonly name: string
    readonly description: string
  }[]
}

