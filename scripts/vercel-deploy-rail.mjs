const PUBLISH_AND_BUILD_COMMAND =
  'bun run --cwd ../seed-drive publish && bun run --cwd ../../apps/api build:vercel'

export function releaseRevisionForRail(env) {
  const revision = env.VERCEL_GIT_COMMIT_SHA
  if (!/^[0-9a-f]{40}$/.test(revision ?? '')) {
    throw new Error('deployment rail: VERCEL_GIT_COMMIT_SHA must be a full lowercase revision')
  }
  return revision
}

export function backendReleaseRevisionSource(revision) {
  const validated = releaseRevisionForRail({ VERCEL_GIT_COMMIT_SHA: revision })
  return `// Generated by the Vercel deployment rail before Convex deploys.\nexport const DEPLOYED_RELEASE_REVISION = '${validated}'\n`
}

export function deploymentRailPlan(vercelEnvironment) {
  const environment = vercelEnvironment === 'production' ? 'production' : 'staging'

  // `convex deploy` authenticates entirely from CONVEX_DEPLOY_KEY (which encodes
  // its target deployment) and its `--cmd` publishes the seed before building
  // the API before functions land. Seed publication must therefore remain
  // compatible with the currently deployed backend. API promotion follows a
  // successful backend push, so backend argument changes need a bounded bridge
  // for the API that still owns the domain. No secret
  // fanout runs in the build. The fanout shells out to the
  // Vercel CLI for all seven projects, which needs their `.vercel` project links
  // (gitignored, absent in a build checkout) and account-scoped token access a
  // build container does not have. Secret changes are rare and pushed
  // deliberately with `bun run secrets:push:<env> -- --apply`, out of band.
  return {
    environment,
    requiredEnvironmentVariables: ['CONVEX_DEPLOY_KEY'],
    steps: [
      {
        cwd: 'packages/backend',
        command: 'bun',
        args: ['run', 'deploy:ci', '--', '--cmd', PUBLISH_AND_BUILD_COMMAND],
      },
    ],
  }
}

export function railMode(plan, env) {
  if (plan.environment === 'staging' && env.VERCEL_GIT_COMMIT_REF !== 'staging') {
    return { mode: 'skip-preview', missing: [] }
  }
  const missing = plan.requiredEnvironmentVariables.filter(name => !env[name])
  if (missing.length === 0) return { mode: 'run', missing }
  if (missing.length === plan.requiredEnvironmentVariables.length) {
    // Not yet bootstrapped: build plainly instead of bricking every deploy.
    return { mode: 'skip-unbootstrapped', missing }
  }
  return { mode: 'fail', missing }
}
