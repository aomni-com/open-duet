import path from 'node:path'

import { PUBLIC_ROUTE_MANIFEST } from '../src/public-route-manifest'

const outputPath = path.resolve(import.meta.dir, '../src/spanish-public-paths.generated.ts')
const spanishPaths = PUBLIC_ROUTE_MANIFEST.map(route => route.publicPath).filter(
  route => route === '/es' || route.startsWith('/es/'),
)
const source = `// Generated by \`bun run public-paths:write\`; verified by verify-public-content.ts.\nexport const SPANISH_PUBLIC_PATHS = ${JSON.stringify(spanishPaths, null, 2)} as const\n`

await Bun.write(outputPath, source)
console.log(`Wrote ${spanishPaths.length} Spanish public paths.`)
