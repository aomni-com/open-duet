export type SpaContextValue = {
  identity: WhoamiResponse
  billingOverview?: UserBillingOverview
  api: SpaApi
  trainUploads: TrainUploadsClient
  activeWorkspaceSlug?: string
  transitionWorkspace(workspaceSlug: string): Promise<WorkspaceSummary | undefined>
  createWorkspace(input: { name: string; slug: string }): Promise<WorkspaceCreateResult>
  logout(): Promise<void>
  onLocaleChange?: (locale: 'en' | 'es-419') => void
  /**
   * Substitute clock for time-dependent presentation (greetings and the
   * counting "thinking for Xs" line). Screenshot fixtures pin it; the product
   * leaves it unset and surfaces use the wall clock. Deliberately a twin of the files
   * library's own pinned clock (`AttributionConfig.now`), not a consumer of
   * it: session presentation takes every input as a prop so it renders
   * without providers, and the attribution config is that library's seam.
   */
  clock?: () => number
}

export const SpaContext = createContext<SpaContextValue | null>(null)

export function useSpa(): SpaContextValue {
  const value = useContext(SpaContext)
  if (value === null) throw new Error('Duet SPA context is missing')
  return value
}
